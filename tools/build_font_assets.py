"""Embed the checked-in offline WOFF2 font in ESP32 program flash."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    data = (ROOT / "assets/fonts/nunito-sans-latin.woff2").read_bytes()
    if data[:4] != b"wOF2":
        raise ValueError("Expected a WOFF2 font")
    header = ["// Generated by tools/build_font_assets.py; do not edit.",
              "#pragma once", "#include <Arduino.h>", "namespace FontAssets {",
              "static const uint8_t nunitoSans[] PROGMEM = {"]
    for offset in range(0, len(data), 16):
        header.append("    " + ",".join(f"0x{byte:02x}" for byte in data[offset:offset+16]) + ",")
    header += ["};", "} // namespace FontAssets\n"]
    (ROOT / "src/FontAssets.h").write_text("\n".join(header))
    print(f"Nunito Sans offline font: {len(data)} bytes")


if __name__ == "__main__":
    main()
