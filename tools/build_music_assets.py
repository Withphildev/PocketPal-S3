"""Embed the supplied MP3 unchanged and the editable Music & Play script."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
track = ROOT / 'assets/music/Short_Afternoon_in_the_Canopy.mp3'
data = track.read_bytes()
header = ['// Generated by tools/build_music_assets.py.', '#pragma once',
          '#include <Arduino.h>', 'namespace MusicPlayAssets {',
          'static const uint8_t track[] PROGMEM = {']
for offset in range(0, len(data), 16):
    header.append('    '+','.join(f'0x{b:02x}' for b in data[offset:offset+16])+',')
header += ['};', 'static const char script[] PROGMEM = R"MPJS(',
           (ROOT / 'src/MusicPlay.js').read_text(), ')MPJS";',
           '} // namespace MusicPlayAssets', '']
(ROOT / 'src/MusicPlayAssets.h').write_text('\n'.join(header))
print(f'Embedded original MP3: {len(data)} bytes; MusicPlay.js synchronized')
