"""Resize supplied splash artwork, preserving its full composition."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/splash'
image = Image.open(ASSETS / 'source/splash.png').convert('RGB')
image = image.resize((240, 135), Image.Resampling.LANCZOS)
target = ASSETS / 'splash.jpg'
image.save(target, quality=95, optimize=True, subsampling=0)
data = target.read_bytes()
header = ['// Generated by tools/build_splash_assets.py.', '#pragma once',
          '#include <Arduino.h>', 'namespace SplashAssets {',
          'static const uint8_t image[] PROGMEM = {']
for offset in range(0, len(data), 16):
    header.append('    '+','.join(f'0x{b:02x}' for b in data[offset:offset+16])+',')
header += ['};', '} // namespace SplashAssets', '']
(ROOT / 'src/SplashAssets.h').write_text('\n'.join(header))
print(f'Splash: 240x135, {len(data)} bytes')
