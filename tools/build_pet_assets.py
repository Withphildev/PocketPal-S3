"""Resize supplied artwork and generate firmware assets; requires Pillow.

Run from any directory after placing the original PNGs in assets/dragon/source.
All poses share a foot baseline and character height. No artwork is redrawn.
"""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
POSES = ("idle", "happy", "listening", "excited", "sleeping", "surprised")
ASSETS = ROOT / "assets" / "dragon"


def normalized(image, size):
    image = image.convert("RGBA")
    bbox = image.getchannel("A").point(lambda a: 255 if a > 16 else 0).getbbox()
    if not bbox:
        raise ValueError("Artwork has no visible pixels")
    cropped = image.crop(bbox)
    # Identical character height and feet baseline with room for tilted heads.
    scale = min((size - 6) / cropped.height, (size - 6) / cropped.width)
    resized = cropped.resize((round(cropped.width * scale), round(cropped.height * scale)), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (size, size))
    canvas.alpha_composite(resized, ((size - resized.width) // 2, size - 3 - resized.height))
    return canvas


def array(name, data):
    lines = [f"static const uint8_t {name}[] PROGMEM = {{"]
    for offset in range(0, len(data), 16):
        lines.append("    " + ",".join(f"0x{byte:02x}" for byte in data[offset:offset + 16]) + ",")
    return "\n".join(lines + ["};"])


def main():
    header = ["// Generated by tools/build_pet_assets.py; do not edit.", "#pragma once", "#include <Arduino.h>",
              "struct PetImage { const uint8_t *data; size_t size; };", "namespace PetAssets {"]
    preview = Image.new("RGB", (720, 210), "#211a36")
    draw = ImageDraw.Draw(preview)
    for index, pose in enumerate(POSES):
        source = Image.open(ASSETS / "source" / f"{pose}.png")
        web = normalized(source, 240)
        device = normalized(source, 80)
        for folder in ("web", "device"):
            (ASSETS / folder).mkdir(parents=True, exist_ok=True)
        web_path = ASSETS / "web" / f"{pose}.png"
        web.save(web_path, optimize=True)
        # A black backing avoids alpha blending work on the device's black UI.
        black = Image.new("RGB", (80, 80))
        black.paste(device, mask=device.getchannel("A"))
        device_path = ASSETS / "device" / f"{pose}.png"
        black.save(device_path, optimize=True)
        header.append(array(f"{pose}Web", web_path.read_bytes()))
        header.append(array(f"{pose}Device", device_path.read_bytes()))
        preview.paste(web.resize((110, 110), Image.Resampling.LANCZOS), (index * 120 + 5, 20),
                      web.resize((110, 110), Image.Resampling.LANCZOS).getchannel("A"))
        preview.paste(black, (index * 120 + 20, 130))
        draw.text((index * 120 + 5, 4), pose, fill="white")
    for variant in ("Web", "Device"):
        header.append(f"static const PetImage {variant.lower()}[] = {{")
        header.extend(f"    {{{pose}{variant}, sizeof({pose}{variant})}}," for pose in POSES)
        header.append("};")
    header.append("} // namespace PetAssets\n")
    (ROOT / "src" / "PetAssets.h").write_text("\n".join(header))
    preview.save(ASSETS / "preview.png")
    print("Generated six 240px browser poses and six 80px device poses.")


if __name__ == "__main__":
    main()
