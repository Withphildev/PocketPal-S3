"""Convert the supplied forest illustration into embedded JPEG backgrounds."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ROOM = ROOT / "assets" / "room"


def main():
    original = Image.open(ROOM / "source" / "forest.png").convert("RGB")
    # Portrait retains the original composition. Landscape focuses on the
    # waterfall and grassy clearing rather than cropping the dragon's ground.
    mobile = original.resize((640, round(original.height * 640 / original.width)), Image.Resampling.LANCZOS)
    landscape = original.crop((0, round(original.height * 0.34), original.width,
                               round(original.height * 0.715)))
    landscape = landscape.resize((960, 480), Image.Resampling.LANCZOS)
    header = ["// Generated by tools/build_room_assets.py; do not edit.", "#pragma once",
              "#include <Arduino.h>", "namespace RoomAssets {"]
    for name, image in (("forestMobile", mobile), ("forestWide", landscape)):
        target = ROOM / f"{name}.jpg"
        image.save(target, quality=86, optimize=True)
        data = target.read_bytes()
        header.append(f"static const uint8_t {name}[] PROGMEM = {{")
        for offset in range(0, len(data), 16):
            header.append("    " + ",".join(f"0x{byte:02x}" for byte in data[offset:offset+16]) + ",")
        header.append("};")
        print(f"{name}: {image.width}x{image.height}, {len(data)} bytes")
    header.append("} // namespace RoomAssets\n")
    (ROOT / "src" / "RoomAssets.h").write_text("\n".join(header))


if __name__ == "__main__":
    main()
