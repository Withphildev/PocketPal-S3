"""Prepare supplied props without redrawing: crop transparent margins and resize."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/props"
NAMES = ("strawberry", "ball", "water", "soap", "bubble", "blanket", "hand")
DEVICE_WIDTHS = (22, 22, 16, 28, 14, 54, 48)


def main():
    header = ["// Generated by tools/build_prop_assets.py; do not edit.", "#pragma once",
              '#include "PetAssets.h"', "namespace PropAssets {"]
    for index, name in enumerate(NAMES):
        image = Image.open(ASSETS / "source" / f"{name}.png").convert("RGBA")
        if image.getpixel((0, 0))[3] != 0:
            raise ValueError(f"{name}: expected transparent background")
        box = image.getchannel("A").point(lambda a: 255 if a > 16 else 0).getbbox()
        if not box:
            raise ValueError(f"{name}: empty artwork")
        image = image.crop(box)
        for variant, width in (("web", 160), ("device", DEVICE_WIDTHS[index])):
            scaled = image.resize((width, max(1, round(image.height * width / image.width))), Image.Resampling.LANCZOS)
            # Transparent border prevents edge clipping and preserves alpha for overlays.
            canvas = Image.new("RGBA", (scaled.width + 4, scaled.height + 4))
            canvas.alpha_composite(scaled, (2, 2))
            folder = ASSETS / variant
            folder.mkdir(parents=True, exist_ok=True)
            target = folder / f"{name}.png"
            canvas.save(target, optimize=True)
            data = target.read_bytes()
            key = name + variant.title()
            header.append(f"static const uint8_t {key}[] PROGMEM = {{")
            for offset in range(0, len(data), 16):
                header.append("    " + ",".join(f"0x{byte:02x}" for byte in data[offset:offset+16]) + ",")
            header.append("};")
            print(f"{name} {variant}: {canvas.width}x{canvas.height}, {len(data)} bytes")
    for variant in ("Web", "Device"):
        header.append(f"static const PetImage {variant.lower()}[] = {{")
        header.extend(f"    {{{name}{variant}, sizeof({name}{variant})}}," for name in NAMES)
        header.append("};")
    header += ['static const char *const names[] = {"strawberry", "ball", "water", "soap", "bubble", "blanket", "hand"};',
               "} // namespace PropAssets\n"]
    (ROOT / "src/PropAssets.h").write_text("\n".join(header))


if __name__ == "__main__":
    main()
